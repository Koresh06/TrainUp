def plan_button_label(plan: SubscriptionPricePlan, monthly_price: Decimal | None) -> str:
    """«6 месяцев — $150 · $25/мес · −17%»: цена за месяц и выгода против
    помесячной оплаты — так длинные тарифы сразу видно как выгодные."""
    name = SUBSCRIPTION_PLAN_LABELS.get(plan.plan, plan.plan.value)
    label = f"{name} — {usd(plan.price)}"
    if not plan.months or plan.months <= 1:
        return label
    per_month = (plan.price / plan.months).quantize(Decimal("0.01"))
    label += f" · {usd(per_month)}/мес"
    if monthly_price:
        saving = 1 - per_month / monthly_price
        if saving >= Decimal("0.01"):
            label += f" · −{saving:.0%}"
    return label


def monthly_base_price(plans: list[SubscriptionPricePlan]) -> Decimal | None:
    """Цена самого короткого тарифа в пересчёте на месяц — база для «выгоды»."""
    shortest = min((p for p in plans if p.months), key=lambda p: p.months, default=None)
    return (shortest.price / shortest.months) if shortest else None


def cheapest_per_day(plans: list[SubscriptionPricePlan]) -> str | None:
    priced = [p.price / (p.months * 30) for p in plans if p.months]
    return usd(min(priced).quantize(Decimal("0.01"))) if priced else None
