from typing import Protocol

from src.domain.entities.client import Client


class ClientRepository(Protocol):
    async def get_all(self) -> list[Client]: ...

    async def get_by_id(self, client_id: int) -> Client | None: ...

    async def get_by_tg_id(self, tg_id: int) -> Client | None: ...

    async def get_by_trainer_id(self, trainer_id: int) -> list[Client]: ...

    async def get_by_invite_token(self, token: str) -> Client | None: ...

    async def get_by_referral_code(self, code: str) -> Client | None: ...

    async def get_referred_by(self, client_id: int) -> list[Client]:
        """Клиенты, пришедшие по приглашению этого клиента."""
        ...

    async def delete(self, client_id: int) -> None: ...

    async def save(self, client: Client) -> Client: ...

    async def search(self, query: str, limit: int = 20) -> list[Client]: ...
